# ── PDF helper ───────────────────────────────────────────────────────────
def _generate_pdf(title: str, lines: list[str]) -> bytes:
    """Create a simple PDF report using fpdf2."""
    try:
        from fpdf import FPDF
    except ImportError:
        st.warning("fpdf2 is not installed - PDF export unavailable.")
        return b""

    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Arial", "B", 18)
    pdf.cell(0, 12, title, ln=True, align="C")
    pdf.ln(6)
    pdf.set_font("Arial", "", 11)
    for line in lines:
        pdf.cell(0, 7, txt=str(line), ln=1)
    pdf.ln(4)
    pdf.set_font("Arial", "I", 9)
    pdf.cell(0, 8, "Generated by Student Success Analytics Platform | Enterprise Edition", align="C")
    return bytes(pdf.output())


